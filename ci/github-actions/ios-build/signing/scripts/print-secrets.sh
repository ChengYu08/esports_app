#!/usr/bin/env sh
set -eu

ROOT_DIR="$(CDPATH= cd "$(dirname "$0")/../.." && pwd)"
CERTS_DIR="${ROOT_DIR}/signing/certs"
PROFILES_DIR="${ROOT_DIR}/signing/profiles"
SECRETS_ENV_PATH="${ROOT_DIR}/secrets.example.env"
MODE="file"

usage() {
  cat <<'EOF'
Usage:
  print-secrets.sh            Write secret key/value pairs to secrets.example.env.
  print-secrets.sh --print    Print secret values for manual copy.
  print-secrets.sh --gh       Print gh secret set commands.
  print-secrets.sh --apply    Write secrets.example.env, then set GitHub Secrets with gh.

Environment:
  IOS_DISTRIBUTION_CERTIFICATE_PASSWORD or P12_PASSWORD
    Optional. Used as the .p12 export password in file/apply mode.
EOF
}

case "${1:-}" in
  "")
    MODE="file"
    ;;
  "--print" | "--stdout")
    MODE="print"
    ;;
  "--gh")
    MODE="gh"
    ;;
  "--apply" | "--gh-apply")
    MODE="apply"
    ;;
  "-h" | "--help")
    usage
    exit 0
    ;;
  *)
    echo "Unknown option: $1" >&2
    usage >&2
    exit 1
    ;;
esac

resolve_single_file_by_extension() {
  search_dir="$1"
  extension="$2"
  label="$3"
  matches_file="$(mktemp "${TMPDIR:-/tmp}/ipa-cli-matches.XXXXXX")"
  find "$search_dir" -maxdepth 1 -type f -iname "*.$extension" | sort > "$matches_file"
  match_count="$(wc -l < "$matches_file" | tr -d ' ')"

  if [ "$match_count" -eq 1 ]; then
    sed -n '1p' "$matches_file"
    rm -f "$matches_file"
    return
  fi

  if [ "$match_count" -eq 0 ]; then
    rm -f "$matches_file"
    echo "Missing required $label file. Put it under: $search_dir" >&2
    exit 1
  fi

  echo "Found multiple $label files under: $search_dir" >&2
  echo "Keep exactly one .$extension file in this directory." >&2
  sed 's/^/ - /' "$matches_file" >&2
  rm -f "$matches_file"
  exit 1
}

base64_file() {
  file_path="$1"
  if base64 --help 2>/dev/null | grep -q -- '-i'; then
    base64 -i "$file_path" | tr -d '\n'
  else
    base64 < "$file_path" | tr -d '\n'
  fi
}

read_p12_password() {
  if [ -n "${IOS_DISTRIBUTION_CERTIFICATE_PASSWORD:-}" ]; then
    printf '%s' "$IOS_DISTRIBUTION_CERTIFICATE_PASSWORD"
    return
  fi
  if [ -n "${P12_PASSWORD:-}" ]; then
    printf '%s' "$P12_PASSWORD"
    return
  fi
  if [ "$MODE" != "file" ] && [ "$MODE" != "apply" ]; then
    printf '<fill-your-p12-export-password>'
    return
  fi
  if [ ! -t 0 ]; then
    echo "Set IOS_DISTRIBUTION_CERTIFICATE_PASSWORD or P12_PASSWORD before running in a non-interactive shell." >&2
    exit 1
  fi

  password=""
  printf 'P12 export password: ' >&2
  stty -echo
  read -r password
  stty echo
  echo >&2
  if [ -z "$password" ]; then
    echo "P12 password is required." >&2
    exit 1
  fi
  printf '%s' "$password"
}

random_password() {
  if command -v openssl >/dev/null 2>&1; then
    openssl rand -base64 24 | tr -d '\n'
  elif [ -r /dev/urandom ]; then
    LC_ALL=C tr -dc 'A-Za-z0-9' < /dev/urandom | head -c 32
  else
    printf 'change-me-keychain-password'
  fi
}

set_github_secret() {
  name="$1"
  value="$2"
  printf '%s' "$value" | gh secret set "$name" >/dev/null
  echo "Set $name"
}

render_secrets_env() {
  cat <<EOF
# Generated by print-secrets.sh. Do not commit filled values.
IOS_DISTRIBUTION_CERTIFICATE_BASE64=$P12_BASE64
IOS_DISTRIBUTION_CERTIFICATE_PASSWORD=$P12_PASSWORD_VALUE
IOS_PROVISION_PROFILE_BASE64=$PROFILE_BASE64
IOS_KEYCHAIN_PASSWORD=$KEYCHAIN_PASSWORD
EOF
}

write_secrets_env_file() {
  umask 077
  temp_path=""
  has_certificate_base64=0; has_certificate_password=0; has_profile_base64=0; has_keychain_password=0
  temp_path="$(mktemp "${SECRETS_ENV_PATH}.tmp.XXXXXX")"
  if [ -f "$SECRETS_ENV_PATH" ]; then
    while IFS= read -r line || [ -n "$line" ]; do
      case "$line" in
        IOS_DISTRIBUTION_CERTIFICATE_BASE64=*) printf 'IOS_DISTRIBUTION_CERTIFICATE_BASE64=%s\n' "$P12_BASE64" >> "$temp_path"; has_certificate_base64=1 ;;
        IOS_DISTRIBUTION_CERTIFICATE_PASSWORD=*) printf 'IOS_DISTRIBUTION_CERTIFICATE_PASSWORD=%s\n' "$P12_PASSWORD_VALUE" >> "$temp_path"; has_certificate_password=1 ;;
        IOS_PROVISION_PROFILE_BASE64=*) printf 'IOS_PROVISION_PROFILE_BASE64=%s\n' "$PROFILE_BASE64" >> "$temp_path"; has_profile_base64=1 ;;
        IOS_KEYCHAIN_PASSWORD=*) printf 'IOS_KEYCHAIN_PASSWORD=%s\n' "$KEYCHAIN_PASSWORD" >> "$temp_path"; has_keychain_password=1 ;;
        *) printf '%s\n' "$line" >> "$temp_path" ;;
      esac
    done < "$SECRETS_ENV_PATH"
  else
    printf '%s\n' '# Generated by print-secrets.sh. Do not commit filled values.' >> "$temp_path"
  fi
  [ "$has_certificate_base64" -eq 1 ] || printf 'IOS_DISTRIBUTION_CERTIFICATE_BASE64=%s\n' "$P12_BASE64" >> "$temp_path"
  [ "$has_certificate_password" -eq 1 ] || printf 'IOS_DISTRIBUTION_CERTIFICATE_PASSWORD=%s\n' "$P12_PASSWORD_VALUE" >> "$temp_path"
  [ "$has_profile_base64" -eq 1 ] || printf 'IOS_PROVISION_PROFILE_BASE64=%s\n' "$PROFILE_BASE64" >> "$temp_path"
  [ "$has_keychain_password" -eq 1 ] || printf 'IOS_KEYCHAIN_PASSWORD=%s\n' "$KEYCHAIN_PASSWORD" >> "$temp_path"
  mv "$temp_path" "$SECRETS_ENV_PATH"
  chmod 600 "$SECRETS_ENV_PATH" 2>/dev/null || true
  echo "Wrote $SECRETS_ENV_PATH"
}

P12_PATH="$(resolve_single_file_by_extension "$CERTS_DIR" "p12" ".p12")"
PROFILE_PATH="$(resolve_single_file_by_extension "$PROFILES_DIR" "mobileprovision" ".mobileprovision")"

echo "Using .p12: $P12_PATH" >&2
echo "Using provisioning profile: $PROFILE_PATH" >&2

if ! find "$CERTS_DIR" -maxdepth 1 -type f -iname "*.cer" | grep -q .; then
  echo "# Optional .cer not found under: $CERTS_DIR" >&2
  echo "# .cer is not used by GitHub Actions directly. Keep it locally only for record and troubleshooting." >&2
fi

KEYCHAIN_PASSWORD="$(random_password)"
P12_BASE64="$(base64_file "$P12_PATH")"
PROFILE_BASE64="$(base64_file "$PROFILE_PATH")"
P12_PASSWORD_VALUE="$(read_p12_password)"

if [ "$MODE" = "file" ]; then
  write_secrets_env_file
  exit 0
fi

if [ "$MODE" = "apply" ]; then
  write_secrets_env_file
  if ! command -v gh >/dev/null 2>&1; then
    echo "GitHub CLI is required for --apply. Install gh or run without --apply and copy values manually." >&2
    exit 1
  fi
  if ! gh auth status >/dev/null 2>&1; then
    echo "GitHub CLI is not authenticated. Run: gh auth login" >&2
    exit 1
  fi

  set_github_secret IOS_DISTRIBUTION_CERTIFICATE_BASE64 "$P12_BASE64"
  set_github_secret IOS_DISTRIBUTION_CERTIFICATE_PASSWORD "$P12_PASSWORD_VALUE"
  set_github_secret IOS_PROVISION_PROFILE_BASE64 "$PROFILE_BASE64"
  set_github_secret IOS_KEYCHAIN_PASSWORD "$KEYCHAIN_PASSWORD"
  echo "Done. Open GitHub Actions and run the iOS build workflow."
  exit 0
fi

if [ "$MODE" = "gh" ]; then
  echo "gh secret set IOS_DISTRIBUTION_CERTIFICATE_BASE64 <<< '$P12_BASE64'"
  echo "gh secret set IOS_DISTRIBUTION_CERTIFICATE_PASSWORD <<< '$P12_PASSWORD_VALUE'"
  echo "gh secret set IOS_PROVISION_PROFILE_BASE64 <<< '$PROFILE_BASE64'"
  echo "gh secret set IOS_KEYCHAIN_PASSWORD <<< '$KEYCHAIN_PASSWORD'"
  exit 0
fi

render_secrets_env

